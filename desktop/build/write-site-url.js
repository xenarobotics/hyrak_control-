// Writes src/site-url.ts from HYRAK_SITE_URL, so the site an installer opens
// is a BUILD-TIME define rather than a literal in app-main.ts.
//
// Runs first in `npm run build` (see package.json). With HYRAK_SITE_URL
// unset it writes the development default, which is also what the checked-in
// file holds, so a dev build leaves git clean. A release build exports
// HYRAK_SITE_URL (CI: the repo variable of the same name) and gets an
// installer pointing at that deployment; the value must be an http(s) origin.
//
// Why a generated source file and not electron-builder's extraMetadata: the
// URL is needed in the main process before `app` is ready and in the
// preload's origin checks; a typed constant is the simplest thing that is
// visible to both and to tsc.
const fs = require('node:fs')
const path = require('node:path')

const DEV_DEFAULT = 'https://dev.xenarobotics.com'
const raw = (process.env.HYRAK_SITE_URL || '').trim()
let url = DEV_DEFAULT
if (raw) {
    let parsed
    try { parsed = new URL(raw) } catch { parsed = null }
    if (!parsed || !/^https?:$/.test(parsed.protocol)) {
        console.error(`HYRAK_SITE_URL must be an http(s) URL, got: ${raw}`)
        process.exit(1)
    }
    url = parsed.origin
}

const out = path.join(__dirname, '..', 'src', 'site-url.ts')
const body = `// GENERATED by build/write-site-url.js (runs as part of \`npm run build\`).
// Do not edit by hand: set HYRAK_SITE_URL at build time instead.
//
// The site this shell opens, baked in at build time. This checked-in copy
// holds the development default so a plain \`tsc\` and a dev \`npm run start\`
// work without the generator; a release build with HYRAK_SITE_URL set
// (CI's repo variable, or the shell exporting it) rewrites it. At runtime
// the environment variable still wins, for pointing a dev build elsewhere.
export const SITE_URL_DEFAULT = ${JSON.stringify(url).replace(/"/g, "'")}
`
const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : ''
if (current !== body) {
    fs.writeFileSync(out, body)
    console.log(`site-url.ts: ${url}${raw ? '' : ' (dev default; set HYRAK_SITE_URL for a release build)'}`)
}
